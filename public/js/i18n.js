export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return (key, vars = {}) => {
    const raw = table[key] ?? STRINGS.en[key] ?? key;
    return raw.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
  };
}
